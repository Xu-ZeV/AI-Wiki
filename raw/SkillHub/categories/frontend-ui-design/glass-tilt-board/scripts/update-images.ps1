<#
  update-images.ps1 - scan an image folder and write the sibling images.js

  Ships with the skill "glass-tilt-board". Copy it into the page folder and run it there.
  A file:// page cannot list a directory, so this script writes the list once.

  index.html loads <script src="images.js"> to learn which pictures to show.
  Re-run it whenever you add or remove pictures.

  Usage (from this folder):
      powershell -ExecutionPolicy Bypass -File .\update-images.ps1

  Custom folders:
      powershell -ExecutionPolicy Bypass -File .\update-images.ps1 -Folder .\images -Out .\images.js

  NOTE: keep this file ASCII-only. Windows PowerShell 5.1 decodes .ps1 files
  without a BOM as ANSI, which would corrupt non-ASCII text.
#>
[CmdletBinding()]
param(
    [string]$Folder,
    [string]$Out
)

$ErrorActionPreference = 'Stop'

# $PSScriptRoot is not reliable inside param() defaults on Windows PowerShell 5.1
$root = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $Folder) { $Folder = Join-Path $root 'images' }
if (-not $Out)    { $Out    = Join-Path $root 'images.js' }

# URL prefix the page puts in front of every file name. images.js sits next to
# index.html, so express the folder relative to that directory. Uri also copes
# with a target on another drive, where it falls back to an absolute file: URL.
$outDir  = Split-Path -Parent ([System.IO.Path]::GetFullPath($Out))
$baseUri = New-Object System.Uri -ArgumentList ($outDir.TrimEnd('\', '/') + [System.IO.Path]::DirectorySeparatorChar)
$dirUri  = New-Object System.Uri -ArgumentList ([System.IO.Path]::GetFullPath($Folder))
$relName = [System.Uri]::UnescapeDataString($baseUri.MakeRelativeUri($dirUri).ToString()).TrimEnd('/')
if ([string]::IsNullOrEmpty($relName)) { $relName = '.' }

$exts = @('.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.bmp', '.svg')

if (-not (Test-Path -LiteralPath $Folder)) {
    New-Item -ItemType Directory -Path $Folder -Force | Out-Null
}

$files = @(
    Get-ChildItem -LiteralPath $Folder -File |
        Where-Object { $exts -contains $_.Extension.ToLowerInvariant() } |
        Sort-Object Name |
        Select-Object -ExpandProperty Name
)

$list = ($files | ForEach-Object { '        "' + $_.Replace('"', '\"') + '"' }) -join ",`r`n"

$js = @"
/* Auto-generated by update-images.ps1 - do not edit by hand;
   it will be overwritten on the next run.
   To add pictures: drop them into the "$relName/" folder and re-run the script. */
window.GLASS_BOARD_IMAGES = {
    folder: "$relName",
    files: [
$list
    ]
};
"@

Set-Content -LiteralPath $Out -Value $js -Encoding UTF8

Write-Host ("Written: {0}" -f ([System.IO.Path]::GetFullPath($Out))) -ForegroundColor Green
Write-Host ("Images : {0}" -f $files.Count) -ForegroundColor Green
if ($files.Count -gt 0) {
    Write-Host ("List   : {0}" -f ($files -join ', '))
} else {
    Write-Warning ("No images found in {0}; the page will show its empty state." -f $relName)
}
